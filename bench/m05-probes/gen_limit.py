"""Пробы M0.5 п. 1: предел линии в 200 тайлов (docs/mechanics/belts.md, «Нарезка»).

Цепочка из 205–216 лент на восток, источники (манипулятор + сундук с юга от тайла) на выбранных
тайлах, сток в голове. Если на хвостовом тайле 0 есть источник, первый отрезок — [0-2], второй
[3-202] (200 тайлов), третий начинается с тайла 203; без него первый отрезок [0-199], второй с тайла 200.
Набор подобран перебором: модель с пределом 200 тайлов расходится с моделью без предела
(и с пределами 199 / 201) в первые сотни тиков — только такие сцены различают предел.
(Сцены вывода — x0 = -105, лента далеко за обычным пределом ±64 мода: нужен мод с LIMIT >= 110,
см. комментарий в tests/fidelity/README.md.)

    python bench/m05-probes/gen_limit.py <папка>
    cargo run --release --bin fuzz_capture -- --scenes <папка> --out <папка-эталонов> --batch 1
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import Scene  # noqa: E402

# (имя, тип ленты, длина, источники (тайлы от хвоста), тиков)
SPECS = [
    # с источником на хвостовом тайле 0: отрезки [0-2] [3-202] [203-...]
    ("lim-t-n206-a", "t", 206, [0, 202, 205], 700),
    ("lim-r-n210-a", "r", 210, [0, 201, 202, 203, 204, 205, 206, 207, 208, 209], 900),
    ("lim-y-n210-a", "y", 210, [0, 201, 202, 203, 204, 205, 206, 207, 208, 209], 900),
    ("lim-t-n211-a", "t", 211, [0, 201, 202, 203, 204, 205, 206, 207, 209, 210], 850),
    ("lim-y-n215-a", "y", 215, [0, 201, 202, 203, 206, 207, 208, 210, 212, 213], 800),
    ("lim-y-n214-a", "y", 214, [0, 201, 203, 204, 206, 210, 212], 950),
    # без источника на тайле 0: отрезки [0-199] [200-...]
    ("lim-y-n213-b", "y", 213, [198, 199, 201, 202, 207, 208, 212], 1150),
    ("lim-y-n208-b", "y", 208, [198, 199, 200, 201, 202, 203, 204, 205, 207], 700),
    ("lim-y-n207-b", "y", 207, [198, 199, 200, 203, 204, 206], 950),
    ("lim-t-n207-b", "t", 207, [199, 200, 206], 500),
]


def build(out):
    for name, bt, n, srcs, ticks in SPECS:
        s = Scene(name, ticks, x0=-105, btype=bt).belts(n)
        for i in srcs:
            s.source(i, "s", 800)
        s.end_sink(n)
        s.write(out)


if __name__ == "__main__":
    build(sys.argv[1])
